    private void btnsavedataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsavedataActionPerformed
        // TODO add your handling code here:
        /*check if stud id is added in the table then give the dialog box of data added successfully
        else give data insertion unsuccessfully with an error as message type dialog box*/
        if(Enquiry_Admission.isenquiry)
        {
            Connection con;
            try 
            {
                con=CommonFunctions.getCon();
                String query="insert into enquiries(stud_id,sub_Name,enquiryDate) values(?,?,?)";
                PreparedStatement pst=con.prepareStatement(query);
                pst.setInt(1, studid);//int int curdate string
                pst.setString(2, (String) cmbsuboff.getSelectedItem());
                
                SimpleDateFormat formatter = new SimpleDateFormat("yyyy-MM-dd");  
                Date date = new Date();  
                pst.setString(3,formatter.format(date));
                
                int cnt=pst.executeUpdate();
                if(cnt==1)
                {
                    JOptionPane.showMessageDialog(this, "Enquiry added Succesfully!","Enquiry Insertion",JOptionPane.INFORMATION_MESSAGE);
                }
                else
                {
                    JOptionPane.showMessageDialog(this, "Enquiry addition Unsuccesful!","Enquiry Insertion",JOptionPane.ERROR_MESSAGE);
                }
                pst.close();
                con.close();
            }
            catch (SQLException e) 
            {
                JOptionPane.showMessageDialog(this, "Enquiry addition Unsuccesful!","Enquiry Insertion",JOptionPane.ERROR_MESSAGE);
            }
        }
        else
        {
            Connection con;
            try 
            {
                con=CommonFunctions.getCon();
                String query="insert into admission(stud_id,sub_Name,admissionDate) values(?,?,?)";
                PreparedStatement pst=con.prepareStatement(query);
                pst.setInt(1, studid);
                pst.setString(2, (String) cmbsuboff.getSelectedItem());
                
                SimpleDateFormat formatter = new SimpleDateFormat("yyyy-MM-dd");  
                Date date = new Date();  
                pst.setString(3,formatter.format(date));
                
                int cnt=pst.executeUpdate();
                if(cnt==1)
                {
                    JOptionPane.showMessageDialog(this, "Admission Succesful!","Admission",JOptionPane.INFORMATION_MESSAGE);
                }
                else
                {
                    JOptionPane.showMessageDialog(this, "Admission Unsuccesful!","Admission",JOptionPane.ERROR_MESSAGE);
                }
                pst.close();
                con.close();
            }
            catch (SQLException e) 
            {
                JOptionPane.showMessageDialog(this, "Admission Unsuccesful!","Admission",JOptionPane.ERROR_MESSAGE);
            }
        }
        dispose();
    }//GEN-LAST:event_btnsavedataActionPerformed

