    private void dbFetchSubNames()
    {
        Connection con;
        try
        {
            con=CommonFunctions.getCon();
            String query="select subName from Subjects";
            Statement st = con.createStatement();
            ResultSet rs;
            rs=st.executeQuery(query);
            while(rs.next())
            {
                cmbsuboff.addItem(rs.getString("subName"));
            }
            st.close();
            con.close();
        } 
        catch (SQLException ex) 
        {
            System.out.println("Exception Caught "+ex);
        }
    }
    private void changeSubDisplayedValues()
    {
        Connection con;
        try
        {
            con=CommonFunctions.getCon();
            String query="select subFees,subDuration from Subjects where subName=?";
            PreparedStatement pst = con.prepareStatement(query);
            pst.setString(1, (String) cmbsuboff.getSelectedItem());
            ResultSet rs;
            rs=pst.executeQuery();
            if(rs.next())
            {
                txtfees.setText(rs.getString("subFees"));
                txtdur.setText(rs.getString("subDuration"));
            }
            pst.close();
            con.close();
        } 
        catch (SQLException ex) 
        {
            System.out.println("Exception Caught "+ex);
        }
    }

