    private void btnaddsubActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnaddsubActionPerformed
        // TODO add your handling code here:
        if(txtaddsub.getText().length()==0 || txtaddfees.getText().length()==0 || txtadddur.getText().length()==0)
        {
            JOptionPane.showMessageDialog(this, "Insertion Unsuccesful!\nSubject or Fees or Duration\nfields can't be empty!","Insertion",JOptionPane.ERROR_MESSAGE);
        }
        else
        {
            Connection con;
            try 
            {
                con=CommonFunctions.getCon();
                String query="insert into Subjects values(?,?,?)";
                PreparedStatement pst=con.prepareStatement(query);
                pst.setString(1, txtaddsub.getText());
                pst.setInt(2, Integer.parseInt(txtaddfees.getText()));
                pst.setInt(3, Integer.parseInt(txtadddur.getText()));
                int cnt=pst.executeUpdate();
                if(cnt==1)
                {
                    JOptionPane.showMessageDialog(this, "Insertion Succesful!","Insertion",JOptionPane.INFORMATION_MESSAGE);
                    cmbsuboff.addItem(txtaddsub.getText());
                }
                else
                {
                    JOptionPane.showMessageDialog(this, "Insertion Unsuccesful!","Insertion",JOptionPane.ERROR_MESSAGE);
                }
                pst.close();
                con.close();
            }
            catch (SQLException e) 
            {
                JOptionPane.showMessageDialog(this, "Insertion Unsuccesful!","Insertion",JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnaddsubActionPerformed

    private void btnupdsubActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdsubActionPerformed
        // TODO add your handling code here:
        Connection con;
        try 
        {
            con=CommonFunctions.getCon();
            PreparedStatement pst;
            if(txtaddfees.getText().length()==0)
            {
                String query="update Subjects set subDuration=? where subName=?";
                pst=con.prepareStatement(query);
                pst.setInt(1, Integer.parseInt(txtadddur.getText()));
                pst.setString(2, txtaddsub.getText());
            }
            else if(txtadddur.getText().length()==0)
            {
                String query="update Subjects set subFees=? where subName=?";
                pst=con.prepareStatement(query);
                pst.setInt(1, Integer.parseInt(txtaddfees.getText()));
                pst.setString(2, txtaddsub.getText());
            }
            else
            {
                String query="update Subjects set subFees=?, subDuration=? where subName=?";
                pst=con.prepareStatement(query);
                pst.setInt(1, Integer.parseInt(txtaddfees.getText()));
                pst.setInt(2, Integer.parseInt(txtadddur.getText()));
                pst.setString(3, txtaddsub.getText());
            }
            int cnt=pst.executeUpdate();
            if(cnt==1)
            {
                JOptionPane.showMessageDialog(this, "Updated Succesfully!","Update",JOptionPane.INFORMATION_MESSAGE);
                changeSubDisplayedValues();
            }
            else
            {
                JOptionPane.showMessageDialog(this, "Update Unsuccesful!\nCheck if subject field has a value.","Update",JOptionPane.ERROR_MESSAGE);
            }
            pst.close();
            con.close();
        }
        catch (SQLException e) 
        {
            JOptionPane.showMessageDialog(this, "Update Unsuccesful!","Update",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnupdsubActionPerformed

