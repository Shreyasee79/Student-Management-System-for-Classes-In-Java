            Statement st=con.createStatement();
            ResultSet rs;
            rs=st.executeQuery(query);
            while(rs.next())
            {
                cmbhome.addItem(rs.getString("hometown"));
            }
            
            query="select clgName from college";
            rs=st.executeQuery(query);
