    private void btnhomeaddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnhomeaddActionPerformed
        // TODO add your handling code here:
        String hometown=JOptionPane.showInputDialog(this, "Enter hometown", "New Value", JOptionPane.QUESTION_MESSAGE);
        if(hometown!=null && hometown.length()!=0)
        {
            try 
            {
                Connection con=CommonFunctions.getCon();
                String query="insert into home_town(hometown) values(?)";
                PreparedStatement pst=con.prepareStatement(query);
                pst.setString(1, hometown);
                int cnt=pst.executeUpdate();
                if(cnt==1)
                {
                    JOptionPane.showMessageDialog(this, "Insertion Succesful!","Insertion",JOptionPane.INFORMATION_MESSAGE);
                    cmbhome.addItem(hometown);
                }
                else
                {
                    JOptionPane.showMessageDialog(this, "Insertion Unsuccesful!","Insertion",JOptionPane.ERROR_MESSAGE);
                }
                pst.close();
                con.close();
            } 
            catch (SQLException e) 
            {
                JOptionPane.showMessageDialog(this, "Insertion Unsuccesful!","Insertion",JOptionPane.ERROR_MESSAGE);
            }
        }
        else
        {
            JOptionPane.showMessageDialog(this, "Insertion Unsuccesful!","Insertion",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnhomeaddActionPerformed

